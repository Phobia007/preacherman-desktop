import { mkdir, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import YAML from "yaml";
import { EVENT_DEFINITIONS } from "./lib/event-definitions.mjs";
import { contractsRoot, readCsv, splitMultiValue } from "./lib/registry.mjs";
import { readFile } from "node:fs/promises";

function literal(value) {
  return value === null ? "null" : JSON.stringify(value);
}

function schemaToType(schema, indent = 0) {
  if (schema.const !== undefined) {
    return literal(schema.const);
  }
  if (schema.enum) {
    return schema.enum.map(literal).join(" | ");
  }
  if (schema.anyOf) {
    return schema.anyOf.map((item) => schemaToType(item, indent)).join(" | ");
  }
  if (Array.isArray(schema.type)) {
    return schema.type.map((type) => schemaToType({ ...schema, type }, indent)).join(" | ");
  }
  if (schema.type === "array") {
    return `ReadonlyArray<${schemaToType(schema.items ?? {}, indent)}>`;
  }
  if (schema.type === "object" || schema.properties) {
    const required = new Set(schema.required ?? []);
    const nextIndent = " ".repeat(indent + 2);
    const closingIndent = " ".repeat(indent);
    const entries = Object.entries(schema.properties ?? {}).map(([key, value]) => (
      `${nextIndent}readonly ${JSON.stringify(key)}${required.has(key) ? "" : "?"}: ${schemaToType(value, indent + 2)};`
    ));
    return entries.length > 0 ? `{\n${entries.join("\n")}\n${closingIndent}}` : "Readonly<Record<string, unknown>>";
  }
  if (schema.type === "string") {
    return "string";
  }
  if (schema.type === "number" || schema.type === "integer") {
    return "number";
  }
  if (schema.type === "boolean") {
    return "boolean";
  }
  if (schema.type === "null") {
    return "null";
  }
  return "unknown";
}

function renderHttp(apiRows, errorCodes) {
  const operations = apiRows.map((row) => {
    const value = {
      method: row.method,
      path: row.path,
      operationId: row.operation_id,
      tag: row.tag,
      executionMode: row.execution_mode,
      permissions: splitMultiValue(row.permissions),
      errorCodes: splitMultiValue(row.error_codes),
    };
    return `  ${JSON.stringify(row.api_id)}: ${JSON.stringify(value)},`;
  });

  return `// Generated by scripts/generate-typescript.mjs. Do not edit by hand.\n\n` +
    `export const API_OPERATIONS = {\n${operations.join("\n")}\n} as const;\n\n` +
    `export const STABLE_ERROR_CODES = ${JSON.stringify(errorCodes)} as const;\n\n` +
    `export type ApiId = keyof typeof API_OPERATIONS;\n` +
    `export type ApiOperation = (typeof API_OPERATIONS)[ApiId];\n` +
    `export type OperationId = ApiOperation["operationId"];\n` +
    `export type StableErrorCode = (typeof STABLE_ERROR_CODES)[number];\n`;
}

function renderEvents(eventRows) {
  const eventTypes = eventRows.map((row) => row.event_type);
  const payloadEntries = eventRows.map((row) => (
    `  readonly ${JSON.stringify(row.event_type)}: ${schemaToType(EVENT_DEFINITIONS[row.event_type].payloadSchema, 2)};`
  ));
  const metadataEntries = eventRows.map((row) => (
    `  ${JSON.stringify(row.event_type)}: ${JSON.stringify({
      schemaVersion: Number(row.schema_version),
      family: row.family,
      resourceTypes: splitMultiValue(row.resource_types),
      terminal: row.terminal === "true",
      sensitivity: row.sensitivity,
    })},`
  ));

  return `// Generated by scripts/generate-typescript.mjs. Do not edit by hand.\n\n` +
    `export const EVENT_TYPES = ${JSON.stringify(eventTypes)} as const;\n\n` +
    `export const EVENT_METADATA = {\n${metadataEntries.join("\n")}\n} as const;\n\n` +
    `export type EventType = (typeof EVENT_TYPES)[number];\n` +
    `export type OperationStatus = "queued" | "running" | "succeeded" | "failed" | "cancelled" | "timed_out";\n\n` +
    `export interface EventPayloadMap {\n${payloadEntries.join("\n")}\n}\n\n` +
    `export interface EventEnvelope<TType extends EventType = EventType> {\n` +
    `  readonly event_id: string;\n` +
    `  readonly stream_id: string;\n` +
    `  readonly sequence: number;\n` +
    `  readonly event_type: TType;\n` +
    `  readonly schema_version: 1;\n` +
    `  readonly resource_type: string;\n` +
    `  readonly resource_id: string;\n` +
    `  readonly operation_id?: string | null;\n` +
    `  readonly correlation_id?: string | null;\n` +
    `  readonly operation_status?: OperationStatus | null;\n` +
    `  readonly domain_status?: string | null;\n` +
    `  readonly stage?: string | null;\n` +
    `  readonly progress?: number | null;\n` +
    `  readonly payload: EventPayloadMap[TType];\n` +
    `  readonly occurred_at: string;\n` +
    `}\n\n` +
    `export type PreachermanEvent = {\n` +
    `  readonly [TType in EventType]: EventEnvelope<TType>;\n` +
    `}[EventType];\n`;
}

function renderIndex() {
  return `// Generated by scripts/generate-typescript.mjs. Do not edit by hand.\n` +
    `export * from "./http.js";\n` +
    `export * from "./events.js";\n`;
}

function renderTsconfig() {
  return `${JSON.stringify({
    compilerOptions: {
      target: "ES2022",
      module: "ESNext",
      moduleResolution: "Bundler",
      strict: true,
      noEmit: true,
      skipLibCheck: true,
    },
    include: ["./*.ts"],
  }, null, 2)}\n`;
}

export async function generateTypescriptContracts(outputDir = join(contractsRoot, "generated/typescript")) {
  const [{ rows: apiRows }, { rows: eventRows }, errorRegistry] = await Promise.all([
    readCsv(join(contractsRoot, "registry/api-operations.csv")),
    readCsv(join(contractsRoot, "registry/event-types.csv")),
    readFile(join(contractsRoot, "registry/error-codes.yaml"), "utf8").then(YAML.parse),
  ]);
  await mkdir(outputDir, { recursive: true });
  await Promise.all([
    writeFile(join(outputDir, "http.ts"), renderHttp(apiRows, Object.keys(errorRegistry))),
    writeFile(join(outputDir, "events.ts"), renderEvents(eventRows)),
    writeFile(join(outputDir, "index.ts"), renderIndex()),
    writeFile(join(outputDir, "tsconfig.json"), renderTsconfig()),
  ]);
  return { apiCount: apiRows.length, errorCount: Object.keys(errorRegistry).length, eventCount: eventRows.length };
}

async function main() {
  const result = await generateTypescriptContracts();
  console.log(`Generated TypeScript contracts api=${result.apiCount} errors=${result.errorCount} events=${result.eventCount}`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await main();
}
